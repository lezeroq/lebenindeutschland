const LOCALES = { de: "de-DE", en: "en-US", ru: "ru-RU" };
let lang = "de";

export function setLang(l) {
  lang = STR[l] ? l : "de";
}

export function t(key, vars) {
  let s = STR[lang][key] ?? STR.de[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

export function relDay(ts) {
  const a = new Date(); a.setHours(0, 0, 0, 0);
  const b = new Date(ts); b.setHours(0, 0, 0, 0);
  const n = Math.round((b - a) / 864e5);
  if (n <= 0) return t("today");
  if (n === 1) return t("tomorrow");
  return t("inDays", { n });
}

export function fmtDateTime(ts) {
  return new Intl.DateTimeFormat(LOCALES[lang], { dateStyle: "medium", timeStyle: "short" }).format(ts);
}

export function fmtMinutes(ms) {
  return `${Math.max(1, Math.round(ms / 60000))} ${t("min")}`;
}

export function fmtNumber(n, digits = 1) {
  return new Intl.NumberFormat(LOCALES[lang], { maximumFractionDigits: digits }).format(n);
}
